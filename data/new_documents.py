if __name__ == "__main__":
    base = Path(__file__).parent
    rows = list(csv.DictReader(open(base / "corpus_phase1.csv", encoding="utf-8")))
    next_id = max(int(r["id"]) for r in rows) + 1
    for i, (title, text, category) in enumerate(NEW_DOCS):
        rows.append({"id": next_id + i, "title": title, "text": text, "category": category})

    with open(base / "corpus.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["id", "title", "text", "category"], quoting=csv.QUOTE_NONNUMERIC)
        writer.writeheader()
        writer.writerows(rows)
    print(f"corpus.csv written with {len(rows)} documents")
